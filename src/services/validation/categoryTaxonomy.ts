/**
 * Normalizes input category strings to canonical platform taxonomy.
 * - Handles common aliases (e.g. tech -> technology, games -> gaming, biz -> business)
 * - Treats 'ai' as an independent first-class category
 * - Case-insensitive and whitespace-tolerant
 * - Preserves unrecognized category labels cleanly for safe fallback evaluation
 */
