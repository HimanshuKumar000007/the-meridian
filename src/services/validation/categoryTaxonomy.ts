    // Gaming aliases
    game: 'gaming',
    games: 'gaming',
    gaming: 'gaming',
    videogames: 'gaming',
    videogame: 'gaming',
    'video-games': 'gaming',
    'video games': 'gaming',

    // Cybersecurity aliases
    cybersecurity: 'cybersecurity',
    cyber: 'cybersecurity',
    infosec: 'cybersecurity',
    security: 'cybersecurity',

    // Apps aliases
    apps: 'apps',
    app: 'apps',
    applications: 'apps',
    application: 'apps',

    // Hardware aliases
    hardware: 'hardware',
    devices: 'hardware',
    gadgets: 'hardware',
    semiconductors: 'hardware',

    // Business aliases
    business: 'business',
